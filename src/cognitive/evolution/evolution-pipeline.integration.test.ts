// SCENARIO 6: LLM draft generator — prompt construction and validation
// ===========================================================================
describe("Pipeline: LLM draft generation", () => {
  it("builds a prompt containing skill-creator spec and candidate info", () => {
    const candidate = complexCandidate();
    const prompt = buildPrompt(candidate);

    expect(prompt).toContain("Task to Analyze");
    expect(prompt).toContain(candidate.taskSummary);
    expect(prompt).toContain(candidate.domain);
    expect(prompt).toContain("SKILL.md");
  });

  it("validates and returns draft from well-formed LLM output", async () => {
    const candidate = complexCandidate();
    const llmOutput = wellFormedSkillMd("test-llm-draft", "LLM generated skill for testing");

    const draft = validateAndRepair(llmOutput, candidate);
    expect(draft.name).toBe("test-llm-draft");
    expect(draft.description).toBeTruthy();
    expect(draft.triggerPhrases.length).toBeGreaterThan(0);
  });

  it("falls back to rule-based draft when LLM output is malformed", async () => {
    const candidate = complexCandidate();
    const draft = validateAndRepair("garbage output without frontmatter", candidate);

    // Should fall back to generateSkillDraft
    expect(draft.name).toBeTruthy();
    expect(draft.description).toBeTruthy();
  });

  it("handles markdown code fence wrapping", async () => {
    const candidate = complexCandidate();
    const content = wellFormedSkillMd("fenced-skill", "Fenced skill");
    const wrapped = "```markdown\n" + content + "\n```";

    const draft = validateAndRepair(wrapped, candidate);
    expect(draft.name).toBe("fenced-skill");
  });

  it("falls back when Triggers section is missing", async () => {
    const candidate = complexCandidate();
    const noTriggers =
      '---\nname: no-triggers\ndescription: "No triggers"\n---\n\n## Workflow\n\n1. Step one.';

    const draft = validateAndRepair(noTriggers, candidate);
    // Falls back to rule-based because no trigger phrases extracted
    expect(draft.name).toBeTruthy();
  });

  it("full generateSkillDraftLLM with mock LLM", async () => {
    const candidate = complexCandidate();
    const goodOutput = wellFormedSkillMd("llm-full-test", "Full LLM generation test");

    const draft = await generateSkillDraftLLM(candidate, {
      generateText: async () => goodOutput,
    });

    expect(draft.name).toBe("llm-full-test");
    expect(draft.triggerPhrases.length).toBeGreaterThan(0);
  });

  it("falls back to rule-based when LLM throws", async () => {
    const candidate = complexCandidate();

    const draft = await generateSkillDraftLLM(candidate, {
      generateText: async () => {
        throw new Error("LLM unavailable");
      },
    });

    // Should still produce a draft via fallback
    expect(draft.name).toBeTruthy();
    expect(draft.description).toBeTruthy();
  });
});

