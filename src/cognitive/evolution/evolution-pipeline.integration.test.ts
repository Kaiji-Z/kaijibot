// SCENARIO 3: Skill patch — text replacement and LLM paths
// ===========================================================================
describe("Pipeline: skill patching", () => {
  it("fast-path: direct text replacement without LLM", async () => {
    await writer.writeSkill({
      name: "test-patch",
      description: "Test skill for patching",
      triggerPhrases: ["test"],
      bodyMarkdown: "## Old Section\n\nOld content here.",
    });

    const patch: SkillPatch = {
      name: "test-patch",
      instructions: "Update the section",
      replacements: [{ oldText: "Old content here.", newText: "New content here." }],
    };

    const result = await engine.patchSkill(patch, { writer });

    expect(result.ok).toBe(true);
    if (result.ok) {
      const raw = await writer.readRawSkill("test-patch");
      expect(raw).toContain("New content here.");
      expect(raw).not.toContain("Old content here.");
    }
  });

  it("returns error when old text not found", async () => {
    await writer.writeSkill({
      name: "test-missing",
      description: "Test",
      triggerPhrases: [],
      bodyMarkdown: "Hello world",
    });

    const result = await engine.patchSkill(
      {
        name: "test-missing",
        instructions: "fix",
        replacements: [{ oldText: "DOES_NOT_EXIST", newText: "x" }],
      },
      { writer },
    );

    expect(result.ok).toBe(false);
    if (!result.ok) {
      expect(result.error).toContain("not found");
    }
  });

  it("LLM path: uses generateText to update skill", async () => {
    await writer.writeSkill({
      name: "test-llm-patch",
      description: "Original",
      triggerPhrases: ["trigger"],
      bodyMarkdown: "## Old",
    });

    const newContent = wellFormedSkillMd("test-llm-patch", "Updated by LLM");
    const mockLlm = async () => newContent;

    const result = await engine.patchSkill(
      { name: "test-llm-patch", instructions: "Rewrite everything" },
      { generateText: mockLlm, writer },
    );

    expect(result.ok).toBe(true);
    if (result.ok) {
      const raw = await writer.readRawSkill("test-llm-patch");
      expect(raw).toContain("Updated by LLM");
    }
  });

  it("returns error when skill does not exist", async () => {
    const result = await engine.patchSkill(
      { name: "ghost-skill", instructions: "update" },
      { generateText: async () => "", writer },
    );
    expect(result.ok).toBe(false);
    if (!result.ok) {
      expect(result.error).toContain("Skill not found");
    }
  });

  it("LLM failure returns error", async () => {
    await writer.writeSkill({
      name: "test-llm-fail",
      description: "Test",
      triggerPhrases: [],
      bodyMarkdown: "Body",
    });

    const failingLlm = async () => {
      throw new Error("API timeout");
    };

    const result = await engine.patchSkill(
      { name: "test-llm-fail", instructions: "Update" },
      { generateText: failingLlm, writer },
    );

    expect(result.ok).toBe(false);
    if (!result.ok) {
      expect(result.error).toContain("Failed to patch");
    }
  });

  it("no replacements and no LLM → error", async () => {
    await writer.writeSkill({
      name: "test-no-llm",
      description: "Test",
      triggerPhrases: [],
      bodyMarkdown: "Body",
    });

    const result = await engine.patchSkill(
      { name: "test-no-llm", instructions: "Change something" },
      { writer },
    );

    expect(result.ok).toBe(false);
    if (!result.ok) {
      expect(result.error).toContain("LLM text generation required");
    }
  });
});

