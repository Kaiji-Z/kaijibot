// SCENARIO 7: Writer edge cases — path safety, atomicity, list
// ===========================================================================
describe("Pipeline: skill writer edge cases", () => {
  it("rejects path traversal in skill name", async () => {
    await expect(
      writer.writeSkill({
        name: "../etc/passwd",
        description: "Evil",
        triggerPhrases: [],
        bodyMarkdown: "Bad",
      }),
    ).rejects.toThrow("Invalid skill name");
  });

  it("rejects absolute path in skill name", async () => {
    await expect(
      writer.writeSkill({
        name: "/tmp/evil",
        description: "Evil",
        triggerPhrases: [],
        bodyMarkdown: "Bad",
      }),
    ).rejects.toThrow("Invalid skill name");
  });

  it("rejects backslash in skill name", async () => {
    await expect(
      writer.writeSkill({
        name: "evil\\skill",
        description: "Evil",
        triggerPhrases: [],
        bodyMarkdown: "Bad",
      }),
    ).rejects.toThrow("Invalid skill name");
  });

  it("listSkillNames returns only valid skill directories", async () => {
    await writer.writeSkill({
      name: "skill-a",
      description: "A",
      triggerPhrases: [],
      bodyMarkdown: "A",
    });
    await writer.writeSkill({
      name: "skill-b",
      description: "B",
      triggerPhrases: [],
      bodyMarkdown: "B",
    });

    const names = await writer.listSkillNames();
    expect(names.toSorted()).toEqual(["skill-a", "skill-b"]);
  });

  it("readSkill returns null for nonexistent skill", async () => {
    const result = await writer.readSkill("does-not-exist");
    expect(result).toBeNull();
  });

  it("readRawSkill returns null for nonexistent skill", async () => {
    const result = await writer.readRawSkill("does-not-exist");
    expect(result).toBeNull();
  });

  it("removeSkill deletes the skill directory", async () => {
    await writer.writeSkill({
      name: "to-remove",
      description: "X",
      triggerPhrases: [],
      bodyMarkdown: "X",
    });
    expect(await writer.skillExists("to-remove")).toBe(true);

    await writer.removeSkill("to-remove");
    expect(await writer.skillExists("to-remove")).toBe(false);
  });

  it("updateSkill overwrites content atomically", async () => {
    await writer.writeSkill({
      name: "update-test",
      description: "Original",
      triggerPhrases: [],
      bodyMarkdown: "Original",
    });

    const newPath = await writer.updateSkill("update-test", "Updated content");
    expect(existsSync(newPath)).toBe(true);

    const raw = await writer.readRawSkill("update-test");
    expect(raw).toBe("Updated content");
  });

  it("updateSkill throws for nonexistent skill", async () => {
    await expect(writer.updateSkill("ghost", "content")).rejects.toThrow("Skill not found");
  });
});

