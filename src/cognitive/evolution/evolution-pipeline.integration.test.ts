// SCENARIO 5: Audit log — records all operations
// ===========================================================================
describe("Pipeline: audit logging", () => {
  it("appends entries and queries them back", async () => {
    await audit.append({
      operation: "skill_suggest",
      actor: "user-1",
      target: "feishu-meeting-archive",
      outcome: "success",
    });

    await audit.append({
      operation: "skill_accept",
      actor: "user-1",
      target: "feishu-meeting-archive",
      outcome: "success",
    });

    const all = await audit.query({ actor: "user-1" });
    expect(all.length).toBe(2);

    const suggests = await audit.query({ operation: "skill_suggest" });
    expect(suggests.length).toBe(1);
    expect(suggests[0].operation).toBe("skill_suggest");
  });

  it("filters by timestamp", async () => {
    await audit.append({
      operation: "old_op",
      actor: "user-1",
      target: "x",
      outcome: "success",
    });

    // Wait to ensure different timestamp
    await new Promise((r) => setTimeout(r, 5));

    await audit.append({
      operation: "new_op",
      actor: "user-1",
      target: "y",
      outcome: "success",
    });

    const recent = await audit.query({ since: Date.now() - 2 });
    expect(recent.length).toBe(1);
    expect(recent[0].operation).toBe("new_op");
  });

  it("returns empty for no matches", async () => {
    const results = await audit.query({ actor: "nobody" });
    expect(results).toEqual([]);
  });
});

